#!/usr/bin/env bash
# ---------------------------------------------------------------
# build_scaling_input.sh
#
# Scans the current directory for  NAME_SCALING_<n>_COEURS  folders,
# runs  getTimePerIter  inside each one, and assembles a plain-text
# input file consumable by  cfd-perf.
#
# Usage:
#   build_scaling_input.sh -c <num_cells> -i <n_iterations> \
#       [-f <num_faces>] [-o <output_file>]       \
#       [-m <mode>] [-e <max_eff_loss>]           \
#       [-M <cores_max>] [-s <stride>]
#
# Required:
#   -c  Number of mesh cells
#   -i  Number of iterations
#
# Optional:
#   -f  Number of mesh faces            (default: 3 × num_cells)
#   -o  Output file                     (default: scaling_input.txt)
#   -m  Optimisation mode               (default: efficiency)
#   -e  Max efficiency loss              (default: 0.3)
#   -M  Max cores to consider           (default: 512)
#   -s  Core stride                     (default: 32)
# ---------------------------------------------------------------
set -euo pipefail

NUM_CELLS=""
NUM_FACES=""
N_ITER=""
OUT_FILE="scaling_input.txt"
MODE="efficiency"
MAX_EFF_LOSS="0.3"
CORES_MAX="512"
STRIDE="32"

usage() {
    echo "Usage: $0 -c <num_cells> -i <n_iterations> [options]" >&2
    echo "  -c  Number of mesh cells (required)" >&2
    echo "  -i  Number of iterations (required)" >&2
    echo "  -f  Number of mesh faces (default: 3*num_cells)" >&2
    echo "  -o  Output file          (default: scaling_input.txt)" >&2
    echo "  -m  Mode                 (default: efficiency)" >&2
    echo "  -e  Max efficiency loss  (default: 0.3)" >&2
    echo "  -M  Cores max            (default: 512)" >&2
    echo "  -s  Stride               (default: 32)" >&2
    exit 1
}

while getopts "c:f:i:o:m:e:M:s:h" opt; do
    case $opt in
        c) NUM_CELLS="$OPTARG" ;;
        f) NUM_FACES="$OPTARG" ;;
        i) N_ITER="$OPTARG" ;;
        o) OUT_FILE="$OPTARG" ;;
        m) MODE="$OPTARG" ;;
        e) MAX_EFF_LOSS="$OPTARG" ;;
        M) CORES_MAX="$OPTARG" ;;
        s) STRIDE="$OPTARG" ;;
        h) usage ;;
        *) usage ;;
    esac
done

if [[ -z "$NUM_CELLS" || -z "$N_ITER" ]]; then
    echo "Error: -c <num_cells> and -i <n_iterations> are required." >&2
    usage
fi

[[ -z "$NUM_FACES" ]] && NUM_FACES=$(( NUM_CELLS * 3 ))

# ---- Discover CASE_SCALING_<n>_COEURS directories ----
dirs=()
for d in *_SCALING_*_COEURS; do
    [[ -d "$d" ]] && dirs+=("$d")
done

if [[ ${#dirs[@]} -eq 0 ]]; then
    echo "Error: no *_SCALING_*_COEURS directories found in $(pwd)" >&2
    exit 1
fi

# ---- Build pilot lines (sorted by core count) ----
pilot_lines=""
for d in "${dirs[@]}"; do
    if [[ ! "$d" =~ ^(.+)_SCALING_([0-9]+)_COEURS$ ]]; then
        echo "Warning: skipping non-matching directory: $d" >&2
        continue
    fi
    cores="${BASH_REMATCH[2]}"

    if [[ -x "$d/getTimePerIter" ]]; then
        time_per_iter=$( cd "$d" && ./getTimePerIter )
    elif [[ -f "$d/getTimePerIter" ]]; then
        time_per_iter=$( cd "$d" && bash getTimePerIter )
    else
        echo "Warning: no getTimePerIter in $d — skipping" >&2
        continue
    fi

    pilot_lines+="pilot ${cores} ${time_per_iter}"$'\n'
done

if [[ -z "$pilot_lines" ]]; then
    echo "Error: could not collect any pilot data." >&2
    exit 1
fi

pilot_sorted=$(echo -n "$pilot_lines" | sort -k2 -n)

# ---- Write output file ----
cat > "$OUT_FILE" <<EOF
# cfd-perf input file
# Generated by build_scaling_input.sh on $(date -Iseconds)
# Directory: $(pwd)

# ---- Mesh ----
num_cells       = ${NUM_CELLS}
num_faces       = ${NUM_FACES}

# ---- Iterations ----
n_iterations    = ${N_ITER}

# ---- Optimisation ----
mode                = ${MODE}
max_efficiency_loss = ${MAX_EFF_LOSS}
cores_max           = ${CORES_MAX}
stride              = ${STRIDE}
min_cells_per_core  = 100000
min_ram_per_core_gb = 0.5

# ---- Pilot measurements ----
# pilot <cores> <time_per_iter_s> [<peak_ram_total_gb>]
${pilot_sorted}
EOF

echo "Input file written to: ${OUT_FILE}"
echo "Pilot points collected: $(echo "$pilot_sorted" | wc -l)"
